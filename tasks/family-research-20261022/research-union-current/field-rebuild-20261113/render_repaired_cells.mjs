import fs from 'node:fs/promises';
import {Workbook} from 'file:///C:/Users/A/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/@oai/artifact-tool/dist/artifact_tool.mjs';
const values=JSON.parse(await fs.readFile('cache/preview-values.json','utf8'));
const labels=['Source window','Price / flow / book path','Mechanics and FIFO','State and delta movie','Candidate discoveries','Source and run hashes'];
const statuses=['Exact metadata','Selected tick path','Recovered adapter features','Selected state/delta history','Original candidate ledger','Reconstruction hashes'];
values[0][2]='Status summary';
for(const [i,row] of values.slice(1).entries()){row[1]=row[1].slice(0,4)+' — '+labels[i];row[2]=statuses[i];}
const book=Workbook.create();
const sheet=book.worksheets.add('Saved cell content preview');
sheet.showGridLines=false;
sheet.getRange('A1:D7').values=values;
sheet.getRange('A1:D7').format.wrapText=true;
sheet.getRange('A1:D7').format.rowHeight=85;
sheet.getRange('A1:D7').format.font.size=11;
sheet.getRange('A1:D7').format.verticalAlignment='center';
sheet.getRange('A1:D7').format.horizontalAlignment='left';
sheet.getRange('A1:D1').format.fill='#18364B';
sheet.getRange('A1:D1').format.font.color='#FFFFFF';
sheet.getRange('A1:D1').format.font.bold=true;
sheet.getRange('A1:D1').format.rowHeight=28;
sheet.getRange('A1:A7').format.columnWidth=12;
sheet.getRange('B1:B7').format.columnWidth=34;
sheet.getRange('C1:C7').format.columnWidth=35;
sheet.getRange('D1:D7').format.columnWidth=80;
book.recalculate();
const preview=await book.render({sheetName:sheet.name,range:'A1:D7',scale:1,format:'png'});
await fs.writeFile('REPAIRED_CELL_CONTENT_PREVIEW.png',new Uint8Array(await preview.arrayBuffer()));
console.log('Saved content preview rendered. This is not a native Excel layout/application check.');
